// Helper function to get all images as flat array
function getAllGalleryImages() {
    const allImages = [];
    for (const [projectKey, images] of Object.entries(projectImages)) {
        const meta = projectMeta[projectKey] || { nameAr: projectKey, nameEn: projectKey, category: 'neon' };
        images.forEach((src, index) => {
            allImages.push({
                src: src,
                project: projectKey,
                nameAr: meta.nameAr,
                nameEn: meta.nameEn,
                category: meta.category,
                tags: meta.tags || [],
                index: index
            });
        });
    }
    return allImages;
}

// Helper function to get images by category
function getImagesByCategory(category) {
    return getAllGalleryImages().filter(img =>
        img.category === category || img.tags.includes(category)
    );
}

// Get total count
function getTotalImageCount() {
    return Object.values(projectImages).reduce((sum, arr) => sum + arr.length, 0);
}

